# ADDING
def add():
    x = int(input("Enter Your First Number For Addition :"))
    y = int(input("Enter Your Second Number For Addition :"))
    result = x + y
    print(result)

add()

# FOR SUBTRACTING
def subtract():
    x = int(input("Enter Your First Number For Subtraction :"))
    y = int(input("Enter Your Second Number For Subtractiom :"))
    result = x - y 
    print(result)

subtract()

# FOR MULTIPLACTION 
def multiply():
    x = int(input("Enter Your First Number For Multiplaction :"))
    y = int(input("Enter Your Second Number For Multiplaction :"))
    result = x * y
    print(result)

multiply()

# FOR DIVISION
def division():
    x = int(input("Enter Your First Number For Division :"))
    y = int(input("Enter Your Second Number For Division :"))
    result = x / y
